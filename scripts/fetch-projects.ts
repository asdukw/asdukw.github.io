// 抓 GitHub 上 pin 的仓库，写进 src/generated/projects.ts。
//
// pinned 只有 GraphQL 的 User.pinnedItems 能给，REST 的 /users/{login}/repos 没有
// 这个字段，所以这里需要一个 token：
//   - 本地：`gh auth token`（或显式设 GH_TOKEN / GITHUB_TOKEN）
//   - CI：deploy.yml 里注入 ${{ github.token }}
//
// 抓不到就保留已经提交的那份 generated 文件，不阻塞构建。

import { site } from "@/lib/site";

const OUTPUT = new URL("../src/generated/projects.ts", import.meta.url);
const TIMEOUT_MS = 15_000;
const LIMIT = 6;

const QUERY = `
  query ($login: String!, $limit: Int!) {
    user(login: $login) {
      pinnedItems(first: $limit, types: [REPOSITORY]) {
        nodes {
          ... on Repository {
            name
            description
            url
            homepageUrl
            stargazerCount
            forkCount
            pushedAt
            primaryLanguage { name }
            repositoryTopics(first: 8) { nodes { topic { name } } }
          }
        }
      }
    }
  }
`;

interface PinnedRepo {
	name: string;
	description: string | null;
	url: string;
	homepageUrl: string | null;
	stargazerCount: number;
	forkCount: number;
	pushedAt: string;
	primaryLanguage: { name: string } | null;
	repositoryTopics: { nodes: { topic: { name: string } }[] };
}

function resolveToken(): string | undefined {
	const fromEnv = process.env.GH_TOKEN ?? process.env.GITHUB_TOKEN;
	if (fromEnv) return fromEnv;

	try {
		const result = Bun.spawnSync(["gh", "auth", "token"], {
			stderr: "ignore",
			stdout: "pipe",
		});
		const token = result.stdout?.toString().trim();
		return result.exitCode === 0 && token ? token : undefined;
	} catch {
		return undefined;
	}
}

// site.github 是唯一的账号来源，不要再写死一次登录名。
function loginFrom(url: string): string {
	return new URL(url).pathname.replace(/^\/+|\/+$/g, "");
}

async function fetchPinned(login: string): Promise<PinnedRepo[]> {
	const token = resolveToken();
	if (!token) {
		throw new Error("没有可用的 GitHub token（设置 GH_TOKEN 或先 gh auth login）");
	}

	const response = await fetch("https://api.github.com/graphql", {
		method: "POST",
		signal: AbortSignal.timeout(TIMEOUT_MS),
		headers: {
			authorization: `bearer ${token}`,
			"content-type": "application/json",
			"user-agent": "asdukw-site-build",
		},
		body: JSON.stringify({ query: QUERY, variables: { login, limit: LIMIT } }),
	});

	if (!response.ok) throw new Error(`HTTP ${response.status}`);

	const payload = (await response.json()) as {
		data?: { user?: { pinnedItems?: { nodes?: PinnedRepo[] } } };
		errors?: { message: string }[];
	};

	if (payload.errors?.length) {
		throw new Error(payload.errors.map((item) => item.message).join("; "));
	}

	return payload.data?.user?.pinnedItems?.nodes ?? [];
}

function toSource(repos: PinnedRepo[]): string {
	const entries = repos.map((repo) => ({
		name: repo.name,
		description: repo.description ?? "",
		url: repo.url,
		homepageUrl: repo.homepageUrl ?? "",
		language: repo.primaryLanguage?.name ?? "",
		topics: repo.repositoryTopics.nodes.map((node) => node.topic.name),
		stars: repo.stargazerCount,
		forks: repo.forkCount,
		// 只保留日期部分：卡片上不展示具体时刻，也避免每次 push 都让文件漂移。
		updated: repo.pushedAt.slice(0, 10),
	}));

	return `// AUTO-GENERATED by scripts/fetch-projects.ts — do not edit by hand.
// 数据来自 GitHub 上 pin 的仓库（GraphQL User.pinnedItems）。
// 改 pin 或改仓库描述后，跑 \`bun run fetch:projects\` 重新生成并提交。

export interface GeneratedProject {
	name: string;
	description: string;
	url: string;
	homepageUrl: string;
	language: string;
	topics: string[];
	stars: number;
	forks: number;
	/** 最近一次 push 的日期，YYYY-MM-DD */
	updated: string;
}

export const PROJECTS: GeneratedProject[] = ${JSON.stringify(entries, null, "\t")};
`;
}

const login = loginFrom(site.github);

try {
	const repos = await fetchPinned(login);
	if (!repos.length) throw new Error(`${login} 没有任何 pin 的仓库`);

	const next = toSource(repos);
	const current = await Bun.file(OUTPUT)
		.text()
		.catch(() => "");

	if (current === next) {
		console.log(`✓ projects.ts 无变化（${repos.length} 个 pinned 仓库）`);
	} else {
		await Bun.write(OUTPUT, next);
		console.log(
			`✓ projects.ts ← ${login} 的 ${repos.length} 个 pinned 仓库：${repos
				.map((repo) => repo.name)
				.join(", ")}`,
		);
	}
} catch (error) {
	const message = error instanceof Error ? error.message : String(error);
	console.warn(`! 拉取 pinned 仓库失败，保留当前 src/generated/projects.ts：${message}`);
}
