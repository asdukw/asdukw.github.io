create or replace function public.upsert_post_translation(
  p_category text,
  p_slug text,
  p_published_on date,
  p_is_published boolean,
  p_lang text,
  p_title text,
  p_excerpt text,
  p_tags text[],
  p_reading_time smallint,
  p_source_mdx text,
  p_body_html text,
  p_toc jsonb
)
returns public.post_translations
language plpgsql
security definer
set search_path = public
as $$
declare
  v_post_id bigint;
  v_translation public.post_translations;
begin
  if not public.current_user_is_admin() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if p_category not in ('blog', 'tech')
     or p_slug is null
     or p_slug !~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,254}$'
     or p_lang not in ('zh', 'en')
     or nullif(btrim(coalesce(p_title, '')), '') is null
     or nullif(btrim(coalesce(p_body_html, '')), '') is null
     or p_reading_time not between 1 and 10000
     or jsonb_typeof(coalesce(p_toc, '[]'::jsonb)) <> 'array' then
    raise exception 'invalid_post' using errcode = '22023';
  end if;

  insert into public.posts (category, slug, published_on, is_published)
  values (p_category, p_slug, p_published_on, coalesce(p_is_published, true))
  on conflict (category, slug) do update set
    published_on = excluded.published_on,
    is_published = excluded.is_published,
    updated_at = now()
  returning id into v_post_id;

  insert into public.post_translations (
    post_id,
    lang,
    title,
    excerpt,
    tags,
    reading_time,
    source_mdx,
    body_html,
    toc
  )
  values (
    v_post_id,
    p_lang,
    btrim(p_title),
    coalesce(p_excerpt, ''),
    coalesce(p_tags, '{}'::text[]),
    p_reading_time,
    coalesce(p_source_mdx, ''),
    p_body_html,
    coalesce(p_toc, '[]'::jsonb)
  )
  on conflict (post_id, lang) do update set
    title = excluded.title,
    excerpt = excluded.excerpt,
    tags = excluded.tags,
    reading_time = excluded.reading_time,
    source_mdx = excluded.source_mdx,
    body_html = excluded.body_html,
    toc = excluded.toc,
    updated_at = now()
  returning * into v_translation;

  return v_translation;
end;
$$;

