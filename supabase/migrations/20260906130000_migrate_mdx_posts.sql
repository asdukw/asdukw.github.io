## Gotchas Hit Along the Way

- `@types/gray-matter` does not exist on npm; gray-matter ships its own types.
- Running the shadcn CLI via `npx` crashes on a missing `@ts-morph/common`; using the local `bun x shadcn` works.
- The Tooltip component from shadcn requires a wrapping `TooltipProvider`.

