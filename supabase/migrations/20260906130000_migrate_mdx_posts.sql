## 踩过的几个坑

- `@types/gray-matter` 在 npm 上不存在，gray-matter 自带类型。
- npx 跑 shadcn CLI 会因缺 `@ts-morph/common` 崩溃，改用本地 `bun x shadcn` 就好了。
- shadcn 的 Tooltip 组件需要在外层包一个 `TooltipProvider`。

